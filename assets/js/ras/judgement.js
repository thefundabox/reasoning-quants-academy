export const POOLS = { assumption: ASSUMPTIONS, action: ACTIONS, argument: ARGUMENTS, conclusion: CONCLUSIONS };

/* Written items skew towards "Only I": that is how they come out when each is
   composed with the implicit one first, and a learner who simply always chose
   "Only assumption I" would have scored better than half. So the two options
   are swapped on half the draws — which is a change of nothing, since I and II
   are not ordered — and the key follows the swap.

   Only where it is safe. Some explanations say "The first names a real harm",
   and swapping those would leave the explanation describing the wrong option,
   so an item whose reason names a POSITION is never swapped. The harness
   checks both halves of that: that the keys come out even, and that no
   swapped item's reason talks about firsts and seconds. */
const swappable = it => !/\b(first|second)\b/i.test(it.why);

const judgement = kind => (R, tier) => {
  /* The tier picks the ITEM, not a knob: the plain ones first, and the "both"
     and "neither" keys — where the second option has to be judged on its own
     after the first already looked right — later. */
  const want = byTier(tier, [1], [1, 2], [2, 3]);
  const pool = POOLS[kind].filter(it => want.includes(it.level));
  const picked = R.pick(pool.length ? pool : POOLS[kind]);
  const flip = swappable(picked) && picked.key < 2 && R() < 0.5;
  const it = flip
    ? { ...picked, a: picked.b, b: picked.a, key: picked.key === 0 ? 1 : 0 }
    : picked;
  const labels = LABELS[kind];
  const key = labels[it.key];
  return ask({
    context: `<b>Statement:</b> ${it.s}<br><br><b>${HEADS[kind]}:</b><br>I. ${it.a}<br>II. ${it.b}`,
    q: ASKS[kind],
    opts: options(key, labels.filter(l => l !== key).map(v => ({ v, why: '' }))),
    why: it.why,
    hardness: 0.8 + it.level * 0.7,
    concept: CONCEPTS[kind][0], conceptLabel: CONCEPTS[kind][1],
    source: 'RAS judgement block — 2015 Q112 · 2016 Q101-104 · 2018 Q102-105 · 2021 Q121-127 · 2023 Q81-83 · 2024 Q79-82, Q86',
  });
};

