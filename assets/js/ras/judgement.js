/* ============================================================
   The judgement questions — assumption, course of action, argument,
   conclusion. About a fifth of the RAS reasoning block, and the one part of
   this bank that cannot be generated.

   WHY THESE ARE WRITTEN AND NOT GENERATED. The others here are generated
   because their answers are derivable: a ratio has a value, a seating has one
   solution. What makes an assumption implicit is a judgement about what a
   sentence takes for granted, and a generator that produced those would be
   producing a FORMULA — "the option that restates the statement is always
   implicit" — which is exactly the habit the paper punishes. So they are
   written one at a time, each with the principle that decides it.

   WHAT DECIDES EACH KIND, stated once so every item can be held to it:

   · Assumption — something the speaker must be taking for granted for the
     statement to make sense at all. Not a consequence, not a restatement in
     stronger words, and never something merely plausible about the world.
   · Course of action — must be practical, proportionate, and aimed at the
     CAUSE. Surrender to pressure, punishment of the victim, and "ban the
     activity" are not courses of action, they are refusals to act.
   · Argument — strong when it bears on the decision with a reason that would
     survive the other side reading it. Weak when it is a slogan, an anecdote,
     an appeal to tradition or authority, or an answer to a different question.
   · Conclusion — must follow from the statement ALONE. Anything that needs
     one fact from outside the passage does not follow, however true it is.

   `level` is the item's difficulty and the tier picks by it: the plain ones
   first, the "both" and "neither" keys — where a candidate must resist
   answering after reading only the first option — later.
   ============================================================ */
